const assert = require('node:assert/strict');
const History = require('./static/position-history.js');
let saved=null;
const storage={getItem:()=>saved,setItem:(_,value)=>{saved=value;}};
const start=1800000000000;
let history=new History(storage,start);
const point=time=>({lat:40,lon:-105,time});
for(let minute=0;minute<=190;minute++) history.accept(point(start+minute*60000),start+minute*60000);
assert.equal(history.points.length,18);
assert.equal(history.points[0].time,start+20*60000);
assert.equal(history.latest.time,start+190*60000);
history=new History(storage,start+191*60000);
assert.equal(history.points.length,18,'refresh restores history');
assert.equal(history.latest.time,start+190*60000,'refresh restores last fix');
history.accept(point(start+190*60000),start+192*60000);
assert.equal(history.points.length,18,'repeated stale sample creates no point');
history.accept({lat:100,lon:0,time:start+192*60000},start+192*60000);
assert.equal(history.latest.lat,40,'invalid coordinates rejected');
history.prune(start+371*60000);
assert.equal(history.points.length,0,'points expire without new telemetry');
assert.equal(history.latest.time,start+190*60000,'last known marker survives expiry');
assert.equal(new History(storage,start+371*60000).points.length,0,'expiry persisted');
assert.equal(History.color(start,start),'hsl(155, 72%, 38%)');
assert.equal(History.color(start,start+History.retention),'hsl(0, 72%, 38%)');
const unavailable=new History({getItem(){throw Error();},setItem(){throw Error();}},start);
unavailable.accept(point(start),start);
assert.equal(unavailable.error,true);
assert.equal(unavailable.points.length,1,'storage failure retains in-memory trail');
console.log('Position history tests passed');
